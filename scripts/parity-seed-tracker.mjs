#!/usr/bin/env node
// Walk dist/ for English page slugs, classify each into a parity-plan bucket,
// and emit parity-tracking.md. Re-runnable; preserves nothing — overwrites the
// file on each run. Hand-edit afterwards.

import { readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = join(here, '..')
const dist = join(repo, 'dist')

const LOCALE_PREFIXES = ['es/', 'ja/', 'ko/', 'pt-BR/']

const VERTICALS = new Set([
  'banking-analytics', 'crm-analytics', 'crypto-analytics', 'education-analytics',
  'embedded-analytics-statistics', 'energy-analytics', 'finance-analytics',
  'healthcare-analytics', 'insurance-analytics', 'isv-analytics', 'it-analytics',
  'manufacturing-analytics', 'mining-analytics', 'on-prem-analytics',
  'real-estate-analytics', 'retail-analytics', 'supply-chain-analytics',
  'telecommunications-analytics', 'white-label-analytics',
])

const VS_COMPETITORS = new Set([
  'reveal-vs-power-bi', 'reveal-vs-tableau', 'reveal-vs-looker', 'reveal-vs-sisense',
  'reveal-vs-domo', 'reveal-vs-metabase', 'reveal-vs-gooddata', 'reveal-vs-thoughtspot',
  'reveal-vs-logi-analytics', 'reveal-vs-luzmo', 'reveal-vs-qrvey', 'reveal-vs-bold-bi',
  'reveal-vs-panintelligence', 'reveal-vs-toucan-toco',
])

const UNIQUE_PRODUCTS = new Set(['features', 'ai', 'pricing', 'embedded-analytics'])

const UNIQUE_LAYOUTS = new Set([
  'about-us', 'annual-reveal-survey-report-top-software-development-challenges-for-2026',
  'careers', 'chart-types', 'cookie-policy', 'data-sources', 'download-sdk',
  'empowering-partners-for-success-with-reveal', 'faq', 'licenses', 'partners',
  'privacy-policy', 'request-demo',
  'reveal-survey-report-top-software-development-challenges-for-2025',
  'security', 'support-policies', 'terms-of-use',
])

const LISTINGS = new Set(['blog', 'glossary', 'stories', 'whitepapers', 'webinars'])

const CHROME_SAVED = new Set([
  '/', '/features/', '/banking-analytics/', '/reveal-vs-power-bi/',
  '/ai/', '/pricing/', '/embedded-analytics/',
])

function walk(dir, base = '') {
  const out = []
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    const rel = base ? `${base}/${name}` : name
    if (statSync(p).isDirectory()) {
      out.push(...walk(p, rel))
    } else if (name === 'index.html') {
      out.push(base ? `/${base}/` : '/')
    }
  }
  return out
}

function isEnglish(path) {
  const trimmed = path.replace(/^\//, '')
  return !LOCALE_PREFIXES.some((p) => trimmed.startsWith(p))
}

function classify(path) {
  if (path === '/') return { bucket: 'homepage', sortKey: '0-home' }
  const trimmed = path.replace(/^\/|\/$/g, '')
  const segments = trimmed.split('/')

  if (segments.length === 2) {
    const [section] = segments
    if (section === 'blog') return { bucket: 'A1 blog', sortKey: '1-A1-' + segments[1] }
    if (section === 'glossary') return { bucket: 'A2 glossary', sortKey: '1-A2-' + segments[1] }
    if (section === 'stories') return { bucket: 'A3 stories', sortKey: '1-A3-' + segments[1] }
    if (section === 'whitepapers') return { bucket: 'A4 whitepapers', sortKey: '1-A4-' + segments[1] }
    if (section === 'webinars') return { bucket: 'A5 webinars', sortKey: '1-A5-' + segments[1] }
    return { bucket: 'unknown', sortKey: '9-' + trimmed }
  }

  const slug = segments[0]
  if (LISTINGS.has(slug)) return { bucket: 'A6 listing', sortKey: '2-A6-' + slug }
  if (VERTICALS.has(slug)) return { bucket: 'B1 vertical', sortKey: '3-B1-' + slug }
  if (VS_COMPETITORS.has(slug)) return { bucket: 'B2 vs-competitor', sortKey: '3-B2-' + slug }
  if (UNIQUE_PRODUCTS.has(slug)) return { bucket: 'B3 unique-product', sortKey: '3-B3-' + slug }
  if (UNIQUE_LAYOUTS.has(slug)) return { bucket: 'C unique-layout', sortKey: '4-C-' + slug }
  if (slug === 'search') return { bucket: 'tooling (search)', sortKey: '5-search' }
  return { bucket: 'unknown', sortKey: '9-' + slug }
}

function originalRef(path) {
  if (path === '/') return '/index.html'
  return path.replace(/\/$/, '') + '.html'
}

function referenceType(path) {
  return CHROME_SAVED.has(path) ? 'chrome-save' : (path.startsWith('/search') ? 'none' : 'wget')
}

const all = walk(dist).filter(isEnglish).sort()
const rows = all.map((p) => {
  const c = classify(p)
  return { path: p, bucket: c.bucket, sortKey: c.sortKey, ref: referenceType(p), original: originalRef(p) }
})
rows.sort((a, b) => a.sortKey.localeCompare(b.sortKey))

const buckets = {}
for (const r of rows) {
  buckets[r.bucket] = (buckets[r.bucket] || 0) + 1
}

const lines = []
lines.push('# Parity tracking — RevealBI Astro migration')
lines.push('')
lines.push(`Generated by \`scripts/parity-seed-tracker.mjs\`. ${rows.length} English pages.`)
lines.push('Hand-edit after seeding. Diff status / fix status updated by Phase-0 harness or by hand.')
lines.push('')
lines.push('**Status legend:** ⚪ not started  🟡 in progress  ❌ diff failing  ✅ matches')
lines.push('**Reference:** `chrome-save` (full fidelity), `wget` (HTML + non-CDN assets), `none`.')
lines.push('')
lines.push('## Inventory')
lines.push('')
for (const [b, n] of Object.entries(buckets)) lines.push(`- ${b}: ${n}`)
lines.push('')
lines.push('## Rows')
lines.push('')
lines.push('| Page | Bucket | Original | Reference | Diff | Fix | Notes |')
lines.push('|---|---|---|---|---|---|---|')
for (const r of rows) {
  const diff = r.path === '/' ? '✅ matches' : '⚪ not run'
  const fix = r.path === '/' ? '✅ done' : '⚪ not started'
  const notes = r.path === '/' ? 'Signed off 2026-04-30' : ''
  lines.push(`| \`${r.path}\` | ${r.bucket} | \`${r.original}\` | ${r.ref} | ${diff} | ${fix} | ${notes} |`)
}
lines.push('')

writeFileSync(join(repo, 'parity-tracking.md'), lines.join('\n'))
console.log(`wrote parity-tracking.md — ${rows.length} rows`)
for (const [b, n] of Object.entries(buckets)) console.log(`  ${b}: ${n}`)
